"""Inputs and expected triangles of the TIN rows of ``vector_generator.VECTOR_GENERATOR`` that need more than a few
round numbers: the conforming mode (its extra points) and the snap of ``snap_tolerance``.

The expected triangles come from JTS 1.20's ``ConformingDelaunayTriangulator`` (and, in the constrained mode, its
``DelaunayTriangulationBuilder`` with the Sloan recovery), run once on these exact inputs: JTS is the reference algorithm
the conforming mode reproduces on every level. Each triangle is its three (x, y) vertices, sorted; the rows judge every
X and Y exactly. The inputs are in general position (no four points on one circle) except the grid, whose ties JTS breaks
its own way.
"""


def points(xyz):
    """``POINT Z`` WKT of each (x, y, z), every number written to round-trip exactly."""
    return [f"POINT Z ({x!r} {y!r} {z!r})" for x, y, z in xyz]


def line(xyz):
    """A ``LINESTRING Z`` WKT through the (x, y, z) vertices."""
    return "LINESTRING Z (" + ", ".join(f"{x!r} {y!r} {z!r}" for x, y, z in xyz) + ")"


def plane(x: float, y: float) -> float:
    """The plane of the square rows: z = 2x + y + 1."""
    return 2.0 * x + y + 1.0


