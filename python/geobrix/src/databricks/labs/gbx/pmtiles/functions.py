def pmtiles_agg(
    bytes: ColLike,
    z: ColLike,
    x: ColLike,
    y: ColLike,
    metadata_json: ColLike = None,
) -> Column:
    """Fold the tiles of a group into one PMTiles v3 archive.

    Args:
        bytes: The tile payload, passed through as it is (PNG, JPEG, WebP or MVT). A
            NULL payload is skipped.
        z: The zoom level of the tile.
        x: The tile column.
        y: The tile row (north-down slippy-map order).
        metadata_json: The archive's metadata as JSON text; NULL, blank or `'{}'` means
            none. SQL default: ``'{}'``.

    Returns:
        The archive bytes, one entry per tile (a repeated tile keeps the first raster
        payload; MVT payloads of one tile merge). A group with no payload gives NULL. A
        group over 100 MiB of payload raises.

    SQL: ``gbx_pmtiles_agg(bytes, z, x, y, [metadata_json])``
    """
    return _api.call(
        "gbx_pmtiles_agg",
        bytes,
        z,
        x,
        y,
        metadata_json,
    )


