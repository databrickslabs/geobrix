"""Tests for scripts/docker/dcs/dcs_lock.py: the DCS image's per-architecture lock and wheelhouse.

Pure Python: no Docker, no network, no package index. The lock is parsed from text; the wheelhouse step
is given a cache that already holds every wheel, so nothing is downloaded.
"""

import hashlib
import importlib.util
import zipfile
from pathlib import Path

import pytest
from conftest import REPO_ROOT

SPEC = importlib.util.spec_from_file_location("dcs_lock", REPO_ROOT / "scripts/docker/dcs/dcs_lock.py")
dcs_lock = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(dcs_lock)

H1, H2, H3 = ("a" * 64, "b" * 64, "c" * 64)
LOCK = f"""\
# autogenerated
click==8.2.1 \\
    --hash=sha256:{H1}
    # via -r core.txt
Idna==3.20 \\
    --hash=sha256:{H1} \\
    --hash=sha256:{H2}
    # via httpx2
numpy==2.3.4 \\
    --hash=sha256:{H3}
rasterio==1.5.2+gbx1 \\
    --hash=sha256:{H2}
    # via -r dcs.in
tippecanoe==2.72.0 \\
    --hash=sha256:{H1}
"""
DIGEST = "sha256:" + "d" * 64
BASE = f"# base-image: databricksruntime/environment@{DIGEST}\nclick==8.2.1\nidna==3.11\nnumpy==2.3.4\nrequests==2.32.5\n"


def test_a_lock_is_read_as_name_version_and_hashes():
    lock = dcs_lock.parse_lock(LOCK)
    assert list(lock) == ["click", "idna", "numpy", "rasterio", "tippecanoe"]
    assert lock["idna"] == ("3.20", [H1, H2])
    assert lock["rasterio"] == ("1.5.2+gbx1", [H2])


def test_only_what_the_base_lacks_or_has_at_another_version_is_fetched():
    need = dcs_lock.needed(dcs_lock.parse_lock(LOCK), dcs_lock.parse_base(BASE))
    assert sorted(need) == ["idna", "rasterio", "tippecanoe"]
    assert dcs_lock.moves(dcs_lock.parse_lock(LOCK), dcs_lock.parse_base(BASE)) == {"idna": ("3.11", "3.20")}


def test_the_constraints_hold_the_base_except_what_the_core_declares_it_moves():
    cons = dcs_lock.constraints(BASE)
    assert "click==8.2.1" in cons.splitlines() and "numpy==2.3.4" in cons.splitlines()
    assert not any(ln.startswith("idna") for ln in cons.splitlines())


def check(lock=LOCK, base=BASE, rasterio="1.5.2+gbx1", sha=None):
    return dcs_lock.check(dcs_lock.parse_lock(lock), dcs_lock.parse_base(base), rasterio, sha)


def test_a_sound_lock_has_no_problems():
    assert check() == []
    assert check(sha=H2) == []


@pytest.mark.parametrize(
    "lock, base, rasterio, sha, expect",
    [
        (LOCK.replace("click==8.2.1", "click==8.5.0"), BASE, "1.5.2+gbx1", None, "click"),
        (LOCK.replace("rasterio==1.5.2+gbx1", "rasterio==1.5.2"), BASE, "1.5.2+gbx1", None, "rasterio"),
        (LOCK, BASE, "1.5.2+gbx1", H3, "sha256"),
        (LOCK.replace(f"    --hash=sha256:{H3}\n", ""), BASE, "1.5.2+gbx1", None, "numpy"),
    ],
    ids=["click-moved", "pypi-rasterio", "wheel-not-in-lock", "unhashed-line"],
)
def test_a_lock_that_moves_click_or_loses_our_rasterio_or_a_hash_is_refused(lock, base, rasterio, sha, expect):
    problems = check(lock, base, rasterio, sha)
    assert problems and any(expect in p for p in problems), problems


def make_wheel(path: Path) -> str:
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("rasterio/__init__.py", "")
    return hashlib.sha256(path.read_bytes()).hexdigest()


def tree(tmp_path, wheel_sha=None):
    root = tmp_path / "repo"
    (root / "scripts/native").mkdir(parents=True)
    (root / "scripts/native/pins.conf").write_text("GBX_NATIVE_REVISION=1\nRASTERIO_VERSION=1.5.2\n")
    dist = root / "build/native/out/aarch64/bindings/dist"
    dist.mkdir(parents=True)
    sha = make_wheel(dist / "rasterio-1.5.2+gbx1-cp312-cp312-linux_aarch64.whl")
    env = root / "python/geobrix/envs/env6"
    env.mkdir(parents=True)
    lock = LOCK.replace(f"rasterio==1.5.2+gbx1 \\\n    --hash=sha256:{H2}", f"rasterio==1.5.2+gbx1 \\\n    --hash=sha256:{wheel_sha or sha}")
    (env / "dcs-aarch64.lock").write_text(lock)
    (env / "dcs-base-aarch64.txt").write_text(BASE)
    (env / "dcs.in").write_text("-r core.txt\n")
    cache = root / "build/dcs/wheelhouse/aarch64"
    cache.mkdir(parents=True)
    for name in ("idna-3.20-py3-none-any.whl", "tippecanoe-2.72.0-py3-none-manylinux_2_28_aarch64.whl"):
        (cache / name).write_bytes(b"w")
    return root


def test_the_wheelhouse_holds_the_needed_wheels_and_our_rasterio(tmp_path):
    root = tree(tmp_path)
    dest = tmp_path / "ctx" / "wheelhouse"
    dcs_lock.wheelhouse(root, "aarch64", dest, download=lambda *a: pytest.fail("a cached wheel was fetched again"))
    assert sorted(p.name for p in dest.iterdir()) == [
        "idna-3.20-py3-none-any.whl",
        "rasterio-1.5.2+gbx1-cp312-cp312-linux_aarch64.whl",
        "tippecanoe-2.72.0-py3-none-manylinux_2_28_aarch64.whl",
    ]


def test_the_wheelhouse_refuses_a_built_rasterio_that_is_not_the_locked_one(tmp_path):
    root = tree(tmp_path, wheel_sha=H3)
    with pytest.raises(dcs_lock.LockError, match="sha256"):
        dcs_lock.wheelhouse(root, "aarch64", tmp_path / "wh", download=lambda *a: None)


def test_a_missing_wheel_is_requested_from_the_index_for_the_target_platform(tmp_path):
    root = tree(tmp_path)
    for p in (root / "build/dcs/wheelhouse/aarch64").iterdir():
        p.unlink()
    asked = []
    def fake(arch, dest, requirements):
        asked.append((arch, requirements))
        for n in ("idna-3.20-py3-none-any.whl", "tippecanoe-2.72.0-py3-none-manylinux_2_28_aarch64.whl"):
            (Path(dest) / n).write_bytes(b"w")
    dcs_lock.wheelhouse(root, "aarch64", tmp_path / "wh", download=fake)
    (arch, reqs), = asked
    assert arch == "aarch64"
    # a hashed requirements file of only the packages the base lacks, never our own rasterio
    assert "idna==3.20" in reqs and "tippecanoe==2.72.0" in reqs and "rasterio" not in reqs
    assert reqs.count("--hash=sha256:") == 3


# --- verify_image.py: the pure parts of the in-image oracle ---------------------------------

VSPEC = importlib.util.spec_from_file_location("verify_image", REPO_ROOT / "scripts/docker/dcs/verify_image.py")
verify_image = importlib.util.module_from_spec(VSPEC)
VSPEC.loader.exec_module(verify_image)


def test_openssl_1_files_are_found_by_name_including_hashed_ones(tmp_path):
    for name in ("libssl.so.1.1", "libcrypto-ab12cd34.so.1.1", "libssl-9d7cc1ed.so.4", "libsslx.so", "libcrypto.so.3"):
        (tmp_path / name).write_text("")
    found = verify_image.openssl1_files([str(tmp_path)])
    assert [Path(p).name for p in found] == ["libcrypto-ab12cd34.so.1.1", "libssl.so.1.1"]


def test_a_process_maps_openssl_1_when_its_maps_name_one():
    maps = (
        "7f00 r-xp 00000000 00:00 1 /x/libssl-9d7cc1ed.so.4\n"
        "7f10 r-xp 00000000 00:00 2 /y/libcrypto.so.1.1\n"
        "7f20 rw-p 00000000 00:00 0\n"
    )
    assert verify_image.maps_openssl1(maps) == ["/y/libcrypto.so.1.1"]
    assert verify_image.maps_openssl1("7f00 r-xp 0 00:00 1 /x/libssl-9d7cc1ed.so.4\n") == []


def test_only_distributions_the_build_installed_are_held_to_the_no_source_build_rule():
    tags = {
        "cryptography": ["cp312-cp312-linux_aarch64"],  # the base image's own
        "rasterio": ["cp312-cp312-linux_aarch64"],  # ours, the one allowed
        "numexpr": ["cp312-cp312-manylinux_2_28_aarch64"],
        "badpkg": ["cp312-cp312-linux_aarch64"],  # built from a source distribution in the image
    }
    built = ["rasterio", "numexpr", "badpkg"]
    assert verify_image.linux_tagged(tags, built, "aarch64") == ["badpkg"]
    assert verify_image.linux_tagged(tags, built, "x86_64") == []


# --- the base image is pinned by digest, and a relock writes both files or neither ---------------


def test_the_base_image_is_the_digest_recorded_in_the_base_list():
    assert dcs_lock.base_image(BASE) == f"databricksruntime/environment@{DIGEST}"
    assert dcs_lock.parse_base(BASE)["click"] == "8.2.1"  # the header is not a package


@pytest.mark.parametrize(
    "text",
    ["click==8.2.1\n", "# base-image: databricksruntime/environment:v6-standard\nclick==8.2.1\n"],
    ids=["no-header", "tag-not-digest"],
)
def test_a_base_list_without_a_digest_pin_is_refused(text):
    with pytest.raises(dcs_lock.LockError, match="digest"):
        dcs_lock.base_image(text)


def scripted(tmp_path, compile_rc):
    """Stand-in for the tools relock calls: docker inspect (digest), docker run (pip list), uv compile."""
    calls = []

    def run(cmd, **kw):
        calls.append(cmd[:3])
        if cmd[:2] == ["docker", "image"]:
            return 0, f'["databricksruntime/environment@{DIGEST}"]'
        if cmd[0] == "docker":
            assert cmd[cmd.index("--entrypoint") + 2] == f"databricksruntime/environment@{DIGEST}"  # the pinned image
            return 0, "click==8.2.1\nidna==3.11\nnewpkg==1.0\n"
        out = Path(cmd[cmd.index("-o") + 1])
        if compile_rc == 0:
            out.write_text(NEW_LOCK)
        return compile_rc, "no solution" if compile_rc else ""

    return run, calls


NEW_LOCK = LOCK.replace("numpy==2.3.4", "newpkg==1.0")


def test_a_failed_compile_leaves_the_old_base_list_and_lock_alone(tmp_path, monkeypatch):
    root = tree(tmp_path)
    env = root / "python/geobrix/envs/env6"
    before = {n: (env / n).read_text() for n in ("dcs-aarch64.lock", "dcs-base-aarch64.txt")}
    run, _ = scripted(tmp_path, compile_rc=2)
    monkeypatch.setattr(dcs_lock, "_run_redacted", run)
    with pytest.raises(dcs_lock.LockError, match="uv pip compile"):
        dcs_lock.relock(root, "aarch64")
    assert {n: (env / n).read_text() for n in before} == before


def test_a_lock_that_fails_its_check_leaves_the_old_pair_alone(tmp_path, monkeypatch):
    root = tree(tmp_path)
    env = root / "python/geobrix/envs/env6"
    before = {n: (env / n).read_text() for n in ("dcs-aarch64.lock", "dcs-base-aarch64.txt")}
    run, _ = scripted(tmp_path, compile_rc=0)  # NEW_LOCK still carries a rasterio hash that is not the built wheel's
    monkeypatch.setattr(dcs_lock, "_run_redacted", run)
    with pytest.raises(dcs_lock.LockError, match="sha256"):
        dcs_lock.relock(root, "aarch64")
    assert {n: (env / n).read_text() for n in before} == before


def test_a_good_relock_writes_both_files_with_the_digest_header(tmp_path, monkeypatch):
    root = tree(tmp_path)
    env = root / "python/geobrix/envs/env6"
    built = next((root / "build/native/out/aarch64/bindings/dist").glob("*.whl"))
    good = LOCK.replace(f"rasterio==1.5.2+gbx1 \\\n    --hash=sha256:{H2}", f"rasterio==1.5.2+gbx1 \\\n    --hash=sha256:{dcs_lock.sha256(built)}")
    run, calls = scripted(tmp_path, compile_rc=0)

    def run_good(cmd, **kw):
        rc, out = run(cmd, **kw)
        if cmd[0] == "uv":
            Path(cmd[cmd.index("-o") + 1]).write_text(good)
        return rc, out

    monkeypatch.setattr(dcs_lock, "_run_redacted", run_good)
    dcs_lock.relock(root, "aarch64")
    base = (env / "dcs-base-aarch64.txt").read_text()
    assert base.splitlines()[0] == f"# base-image: databricksruntime/environment@{DIGEST}"
    assert "newpkg==1.0" in base and (env / "dcs-aarch64.lock").read_text() == good


# --- verify_image.py: exactly one payload libssl ----------------------------------------------


def test_the_payload_libssl_must_be_exactly_one_soname_of_version_3_or_later():
    ok = {"libssl.so.4": "libssl-9d7cc1ed.so.4", "libgdal.so.39": "libgdal-faff949c.so.39"}
    assert verify_image.payload_libssl(ok) == ["libssl-9d7cc1ed.so.4"]
    assert verify_image.payload_libssl({"libssl.so.1.1": "libssl-aa.so.1.1"}) == []
    two = {**ok, "libssl.so.3": "libssl-bb.so.3"}
    assert verify_image.payload_libssl(two) == ["libssl-9d7cc1ed.so.4", "libssl-bb.so.3"]  # the oracle fails on two
