"""The replacement gates (run by gbx:manifest:gen --check): per-surface completeness, `since`, session/UC overlap
parity, parameter names per surface, and the docs-tab guards against the availability matrix.

Each gate returns one finding per line, naming the function and the file. They read the manifest, the
generated modules, the light API sources, the Scala wrappers, function-info.json and the docs pages.
"""

from __future__ import annotations

import ast
import json
import re
from pathlib import Path
from typing import Dict, Iterable, List, Optional

REPO = Path(__file__).resolve().parents[2]
PKG = REPO / "python/geobrix/src/databricks/labs/gbx"
SCALA = REPO / "src/main/scala/com/databricks/labs/gbx"
DOCS = REPO / "docs/docs"
FUNCTION_INFO = REPO / "src/main/resources/com/databricks/labs/gbx/function-info.json"
# The lightweight Python API: public defs that still exist beside the generated entries.
LIGHT_FILES = (
    PKG / "pyrx/functions.py",
    PKG / "pygx/functions.py",
    PKG / "pyvx/functions.py",
)
PY_BEGIN = "# BEGIN GENERATED by gbx:manifest:gen"
PY_END = "# END GENERATED"

# The UC type a session parameter may take (same name, same position): equal types, a geometry
# interchange becoming GEOMETRY (UC takes GEOMETRY only), and the polymorphic BNG resolution narrowed to one type.
UC_TYPE_OK = {
    "BINARY|STRING": frozenset({"GEOMETRY"}),
    "INT|STRING": frozenset({"STRING", "INT"}),
}
_NAME = re.compile(r"[a-z][a-z0-9_]*")
_SCALA_DEF = re.compile(r"def ([a-z][a-z0-9_]*)\(([^)]*)\)\s*:\s*Column")


def _rel(path: Path) -> str:
    return str(path.relative_to(REPO)) if path.is_relative_to(REPO) else str(path)


def _session_key(p) -> str:
    return "|".join(p.session)


# --------------------------------------------------------------------------------------------------- G1


def oracle_findings(fns: Iterable) -> List[str]:
    """Every stable row has a row in its oracle table, and its example is a single-row case of it."""
    from databricks.labs.gbx.bench import oracles

    out = []
    for fn in fns:
        if fn.status != "stable":
            continue
        try:
            table = oracles.TABLES[fn.oracle]
        except KeyError:
            out.append(f"{fn.sql_name}: oracle table {fn.oracle!r} does not exist")
            continue
        rows = [c for c in table if c.fn == fn.sql_name]
        if not rows:
            out.append(f"{fn.sql_name}: no row in {fn.oracle}")
        ex = [c for c in rows if c.cid == fn.example]
        if not ex or ex[0].variants:
            out.append(
                f"{fn.sql_name}: example {fn.example!r} is not a single-row case of {fn.oracle}"
            )
    return out


def _module_file(module: str) -> Path:
    return PKG / module.replace(".", "/") / "functions.py"


def _generated_region(path: Path) -> str:
    text = path.read_text()
    start, end = text.find(PY_BEGIN), text.find(PY_END)
    return text[start:end] if 0 <= start < end else ""


def _defines(ref: str) -> bool:
    """'pkg.mod:attr' names a module file of this repo that defines attr (read, not imported)."""
    mod, _, attr = ref.partition(":")
    base = REPO / "python/geobrix/src" / mod.replace(".", "/")
    path = (
        base.with_suffix(".py")
        if base.with_suffix(".py").exists()
        else base / "__init__.py"
    )
    if not path.exists():
        return False
    return bool(
        re.search(
            rf"^(def|class) {re.escape(attr)}\b|^{re.escape(attr)}\s*[:=]",
            path.read_text(),
            re.M,
        )
    )


_TOP_LEVEL = re.compile(
    r"^(?:object|(?:case |abstract |final |sealed )*class|(?:sealed )?trait)\s", re.M
)


def _declares_name(text: str, obj: str, sql_name: str) -> bool:
    """``object <obj>`` in ``text`` defines its ``name`` as ``sql_name``: the body of that object only, up to
    the next top-level declaration, so a name quoted by another object of the file does not count.
    """
    m = re.search(rf"^object {re.escape(obj)}\b", text, re.M)
    if not m:
        return False
    nxt = _TOP_LEVEL.search(text, m.end())
    body = text[m.end() : nxt.start() if nxt else len(text)]
    return bool(
        re.search(rf'\b(?:def|val)\s+name\b[^=\n]*=\s*"{re.escape(sql_name)}"', body)
    )


_MODULE_OF_PREFIX = {
    "rst": "rasterx",
    "bng": "gridx.bng",
    "quadbin": "gridx.quadbin",
    "custom": "gridx.custom",
    "h3": "gridx.h3",
    "st": "vectorx",
    "pmtiles": "pmtiles",
}


def _scala_functions_file(fn) -> Path:
    """The functions.scala of the row's own package (its Python module's family): wrappers of the same name in
    another package are not this row's."""
    module = (
        fn.python.module
        if fn.python
        else _MODULE_OF_PREFIX.get(fn.sql_name.split("_")[1], "unknown")
    )
    return SCALA / module.replace(".", "/") / "functions.scala"


def completeness_findings(man, fns: Iterable) -> List[str]:
    """G1: each surface a row has exists in its implementation (the binding-parity check, from the manifest)."""
    info = json.loads(FUNCTION_INFO.read_text()).get("functions", {})
    wrappers = _scala_wrappers()
    out = []
    for fn in fns:
        if "L3" not in fn.levels:
            out.append(
                f"{fn.sql_name}: no L3 level (session SQL needs a lightweight implementation)"
            )
        if fn.status != "stable":
            continue
        if fn.sql_name not in info:
            out.append(f"{fn.sql_name}: no entry in {_rel(FUNCTION_INFO)}")
        docs_name = fn.python.name if fn.python else fn.sql_name[len("gbx_") :]
        if fn.python is not None:
            path = _module_file(fn.python.module)
            if not path.exists() or f"def {fn.python.name}(" not in _generated_region(
                path
            ):
                out.append(
                    f"{fn.sql_name}: no generated Python entry {fn.python.name} in {_rel(path)}"
                )
        page = DOCS / f"{fn.doc.page}.mdx"
        if not page.exists() or f"\n### {docs_name}\n" not in page.read_text():
            out.append(
                f"{fn.sql_name}: no section '### {docs_name}' in docs/docs/{fn.doc.page}.mdx"
            )
        l4 = fn.levels.get("L4", {})
        if "handler" in l4 and not _defines(l4["handler"]):
            out.append(f"{fn.sql_name}: its UC handler {l4['handler']} is not defined")
        if "tvf_over" in l4 and l4["tvf_over"] not in man.functions:
            out.append(
                f"{fn.sql_name}: its UC table function reads {l4['tvf_over']}, which has no row"
            )
        if "scala" in fn.surfaces:
            fqn = fn.levels["L1"]["companion"]
            pkg, _, obj = fqn.rpartition(".")
            src = REPO / "src/main/scala" / pkg.replace(".", "/")
            if not any(
                _declares_name(t, obj, fn.sql_name)
                for t in (p.read_text() for p in src.glob("*.scala"))
            ):
                out.append(
                    f"{fn.sql_name}: its L1 companion {fqn} does not declare that name"
                )
            name = fn.python.name if fn.python else fn.sql_name[len("gbx_") :]
            if _rel(_scala_functions_file(fn)) not in wrappers.get(name, {}):
                out.append(
                    f"{fn.sql_name}: the Scala surface has no wrapper {name} in {_rel(_scala_functions_file(fn))}"
                )
    return out


_SINCE = re.compile(r"\d+\.\d+\.\d+")


def since_findings(fns: Iterable) -> List[str]:
    """Every stable row says the release that first shipped it (check-since.py no longer reads these rows)."""
    return [
        f"{fn.sql_name}: `since` {fn.since!r} is not a version like 0.4.0"
        for fn in fns
        if fn.status == "stable" and not _SINCE.fullmatch(fn.since)
    ]


# --------------------------------------------------------------------------------------------------- G2


def overlap_findings(fns: Iterable) -> List[str]:
    """G2: a name on session and UC has the same parameter names, order, arity and defaults; each UC type is a
    form of the session type (GEOMETRY for a geometry interchange, one type of a polymorphic one).
    """
    out = []
    for fn in fns:
        if "L4" not in fn.levels or "tvf_over" in fn.levels["L4"]:
            continue
        for p in fn.params:
            ok = (
                {p.session[0]}
                | UC_TYPE_OK.get(_session_key(p), frozenset())
                | set(p.session)
            )
            if p.uc not in ok:
                out.append(
                    f"{fn.sql_name}: UC type {p.uc!r} of {p.name} is not a form of its session type {_session_key(p)}"
                )
        ret_ok = {fn.returns_session} | (
            {"GEOMETRY"} if fn.returns_session == "BINARY" else set()
        )
        if fn.returns_uc not in ret_ok:
            out.append(
                f"{fn.sql_name}: UC returns {fn.returns_uc}, session returns {fn.returns_session}"
            )
    return out


def collision_findings(man) -> List[str]:
    """Every routine carries gbx_; no private UC name (gbx__<x>) equals a public manifest name; no duplicate rows."""
    raw = json.loads((PKG / "manifest/functions.json").read_text())
    names = [r["sql_name"] for r in raw["functions"]]
    out = [
        f"{n}: two manifest rows"
        for n in sorted({n for n in names if names.count(n) > 1})
    ]
    public = set(names)
    for fn in man.functions.values():
        if not fn.sql_name.startswith("gbx_") or fn.sql_name.startswith("gbx__"):
            out.append(
                f"{fn.sql_name}: a routine name must start gbx_ (private names gbx__ are the manager's)"
            )
        if any(p.default for p in fn.params) and f"gbx__{fn.sql_name[4:]}" in public:
            out.append(f"{fn.sql_name}: its UC private function name is a public name")
    return out


# --------------------------------------------------------------------------------------------------- G3


def _snake(name: str) -> str:
    return re.sub(r"(?<!^)([A-Z])", r"_\1", name).lower()


def _scala_wrappers() -> Dict[str, Dict[str, list]]:
    """Per-name Scala wrapper overloads in <pkg>/functions.scala: {python name: {file: [[param, ...], ...]}}."""
    found: Dict[str, Dict[str, list]] = {}
    for path in sorted(SCALA.rglob("functions.scala")):
        for m in _SCALA_DEF.finditer(path.read_text()):
            args = [a.split(":")[0].strip() for a in m.group(2).split(",") if a.strip()]
            found.setdefault(m.group(1), {}).setdefault(_rel(path), []).append(args)
    return found


def _py_params(
    path: Path, name: str, region: bool = False
) -> Optional[List[List[str]]]:
    """The parameter lists of every top-level ``def name`` in a file (the generated region only, when asked);
    None when there is none. A ``*args`` def (a stub that raises) gives no list."""
    if not path.exists():
        return None
    text = _generated_region(path) if region else path.read_text()
    if region:
        text = "\n".join(ln for ln in text.splitlines() if not ln.startswith(PY_BEGIN))
    found = []
    for node in ast.parse(text).body:
        if isinstance(node, ast.FunctionDef) and node.name == name:
            if node.args.vararg is not None:
                continue
            found.append(
                [
                    a.arg
                    for a in node.args.posonlyargs
                    + node.args.args
                    + node.args.kwonlyargs
                ]
            )
    return found if found else None


def name_findings(fns: Iterable) -> List[str]:
    """G3: parameter names are snake_case, and every surface spells them as the manifest does: the generated
    Python entry, the lightweight API, the Scala wrappers and the function-info usage.
    """
    from databricks.labs.gbx.manifest import PY_EXTRAS

    wrappers = _scala_wrappers()
    info = json.loads(FUNCTION_INFO.read_text()).get("functions", {})
    out = []
    for fn in fns:
        names = [p.name for p in fn.params]
        for p in fn.params:
            if not _NAME.fullmatch(p.name):
                out.append(f"{fn.sql_name}: parameter {p.name!r} is not snake_case")
        extras = (
            tuple(PY_EXTRAS[fn.python.extras]) if fn.python and fn.python.extras else ()
        )
        clash = set(extras) & set(names)
        if clash:
            out.append(
                f"{fn.sql_name}: Python-only keywords {sorted(clash)} collide with parameters"
            )
        py_name = fn.python.name if fn.python else fn.sql_name[len("gbx_") :]
        if fn.python is not None:
            path = _module_file(fn.python.module)
            for got in _py_params(path, py_name, region=True) or ():
                got = [a for a in got if a not in extras]
                got = (
                    got[1:] if got[:1] == ["df"] else got
                )  # a generator entry takes the DataFrame first
                # a table function's entry takes the DataFrame for its table argument (the first parameter)
                if got != (names[1:] if fn.table_input is not None else names):
                    out.append(
                        f"{fn.sql_name}: the generated entry in {_rel(path)} takes {got}, the manifest {names}"
                    )
        for path in LIGHT_FILES:
            for got in _py_params(path, py_name) or ():
                # The lightweight API may carry trailing Python-only keywords; the manifest names come first.
                if got[: len(names)] != names:
                    out.append(
                        f"{fn.sql_name}: the lightweight {py_name} in {_rel(path)} takes {got[: len(names)]}, "
                        f"the manifest {names}"
                    )
        if fn.status == "stable" and fn.sql_name in info:
            usage = [
                a.strip().strip("[]").strip()
                for a in info[fn.sql_name].get("usage_args", "").split(",")
            ]
            if [a for a in usage if a] != names:
                out.append(
                    f"{fn.sql_name}: the usage in {_rel(FUNCTION_INFO)} names {usage}, the manifest {names}"
                )
        own = _rel(_scala_functions_file(fn))
        for file, overloads in wrappers.get(py_name, {}).items():
            if file != own:
                continue
            # Convenience overloads that fill constants take fewer arguments; only more than the signature is wrong
            # (the L1 arity itself is pinned by test_l1_arity_contract_for_every_companion).
            bad = sorted({len(a) for a in overloads if len(a) > fn.max_args})
            if bad:
                out.append(
                    f"{fn.sql_name}: Scala wrapper arities {bad} above {fn.max_args} in {file}"
                )
            for args in sorted({tuple(a) for a in overloads}):
                got = [_snake(a) for a in args]
                if got != names[: len(got)]:
                    out.append(
                        f"{fn.sql_name}: the Scala wrapper in {file} takes {list(args)}, the manifest {names}"
                    )
            # An engine row's wrappers are deleted at its engine switch, not here.
            if "scala" not in fn.surfaces and fn.gdal is None:
                out.append(
                    f"{fn.sql_name}: a Scala wrapper exists in {file} but the row has no L1 companion "
                    "(delete the wrapper)"
                )
    return out


# --------------------------------------------------------------------------------------------------- G4

# A FunctionExamples tab prop: (the surface it shows, the example-function suffix in its source file).
_TABS = {
    "sql": ("session", "_sql_example"),
    "ucSql": ("uc", "_uc_sql_example"),
    "python": ("python", "_python_example"),
    "pythonLight": ("python", "_python_light_example"),
    "scala": ("scala", "_scala_example"),
}


def _defined_names(path: Path) -> set:
    text = path.read_text()
    if path.suffix == ".py":
        names = set()
        for node in ast.walk(ast.parse(text)):
            if isinstance(node, ast.FunctionDef):
                names.add(node.name)
            elif isinstance(node, ast.Assign):
                names.update(t.id for t in node.targets if isinstance(t, ast.Name))
        return names
    return set(re.findall(r"\b(?:def|val)\s+([A-Za-z0-9_]+)", text))


def docs_findings(fns: Iterable) -> List[str]:
    """G4: a function's hand-written tabs match the availability matrix: a tab only for a surface it has, one
    Python tab (no lightweight/heavyweight split), and each tab's example and output exist in its source.
    """
    out = []
    pages: dict = {}
    sources: dict = {}
    for fn in fns:
        if fn.status != "stable" or fn.python is None:
            continue
        page = DOCS / f"{fn.doc.page}.mdx"
        text = pages.setdefault(page, page.read_text())
        m = re.search(
            r'<FunctionExamples\s+name="%s"(.*?)/>' % re.escape(fn.python.name),
            text,
            re.S,
        )
        if not m:
            continue  # the generated example stands in for a function with no hand-written tabs
        props = set(re.findall(r"(\w+)=\{", m.group(1)))
        files = dict(re.findall(r'(\w+)Source="([^"]+)"', m.group(1)))
        if "pythonHeavy" in props:
            out.append(
                f"{fn.sql_name}: a 'pythonHeavy' tab (the Python API is one; drop it) in {_rel(page)}"
            )
        if {"python", "pythonLight"} <= props:
            out.append(
                f"{fn.sql_name}: both a 'python' and a 'pythonLight' tab (keep one) in {_rel(page)}"
            )
        for prop in sorted(props & set(_TABS)):
            surface, suffix = _TABS[prop]
            if surface not in fn.surfaces:
                out.append(
                    f"{fn.sql_name}: a {prop!r} tab for a surface it does not have ({_rel(page)})"
                )
                continue
            src = files.get(prop)
            if not src:
                out.append(
                    f"{fn.sql_name}: the {prop!r} tab names no {prop}Source ({_rel(page)})"
                )
                continue
            path = REPO / src
            if not path.exists():
                out.append(
                    f"{fn.sql_name}: the {prop!r} tab's source {src} does not exist"
                )
                continue
            defined = sources.setdefault(path, _defined_names(path))
            for want in (fn.python.name + suffix, fn.python.name + suffix + "_output"):
                if want not in defined:
                    out.append(f"{fn.sql_name}: the {prop!r} tab needs {want} in {src}")
    return out


def legacy_findings(fns: Iterable) -> List[str]:
    """A stable manifest row has no public def of its Python name in the lightweight modules: the
    generated entry is the one Python name (no aliases)."""
    public = {}
    for path in LIGHT_FILES:
        for node in ast.parse(path.read_text()).body:
            if isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
                public[node.name] = path
    return [
        f"{fn.sql_name}: {_rel(public[fn.python.name])} still defines {fn.python.name} "
        f"(the generated entry is {fn.python.module}.functions.{fn.python.name})"
        for fn in fns
        if fn.status == "stable" and fn.python and fn.python.name in public
    ]


def run() -> List[str]:
    from databricks.labs.gbx import manifest

    manifest.load.cache_clear()
    man = manifest.load()
    fns = sorted(man.functions.values(), key=lambda f: f.sql_name)
    return (
        oracle_findings(fns)
        + completeness_findings(man, fns)
        + since_findings(fns)
        + overlap_findings(fns)
        + collision_findings(man)
        + name_findings(fns)
        + docs_findings(fns)
        + legacy_findings(fns)
    )


if __name__ == "__main__":
    import sys

    found = run()
    print("\n".join(found) or "check_surfaces: OK")
    sys.exit(1 if found else 0)
