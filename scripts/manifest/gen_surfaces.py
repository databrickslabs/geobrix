"""gbx:manifest:gen: write (--write) or verify (--check) every surface generated from the function manifest."""

from __future__ import annotations

import argparse
import ast
import difflib
import json
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional

sys.path.insert(0, str(Path(__file__).resolve().parent))
import surfaces as S  # noqa: E402

REPO = S.REPO
MANIFEST_JSON = S.PKG / "manifest/functions.json"
FUNCTION_INFO = REPO / "src/main/resources/com/databricks/labs/gbx/function-info.json"
AVAILABILITY = REPO / "docs/docs/api/availability.mdx"
EXAMPLES = REPO / "docs/tests/python/api/generated_examples.py"
EXAMPLES_HEADER = (
    '"""GENERATED by gbx:manifest:gen from each function\'s oracle row: one SQL example per function.\n\n'
    "Run by test_generated_examples.py; shown on a function's page when it has no hand-written example.\n"
    '"""\n\n'
)
SURFACE_KEYS = (
    "manifest",
    "python",
    "docs",
    "function-info",
    "availability",
    "examples",
    "counts",
)
_MACHINE_PATH = re.compile(r"/(Users|home|root)/[A-Za-z0-9_.-]+")
_TIER_LINE = re.compile(r"^<Tier [^>]*/>( *<Impl [^>]*/>)?\n", re.M)
_SIGNATURE = re.compile(r"^\*\*Signature:\*\*(.*?)(?:\n\n|\Z)", re.M | re.S)
# A hand-written parameter list beside the generated table: the table is the one source, so it goes.
_PARAMETERS = re.compile(r"^\*\*Parameters:\*\*[^\n]*\n(?:[^\n]+\n)*\n?", re.M)


def read(path: Path) -> str:
    return path.read_text()


def _canonical_manifest(raw: dict) -> str:
    """Rows in (family, sql_name) order, one JSON object per line, so rows of different families land in
    different hunks and a merge (beta into streamline, or another lane's rows) stays readable.
    """
    rows = sorted(raw["functions"], key=lambda r: (r["family"], r["sql_name"]))
    head = json.dumps(
        {k: v for k, v in raw.items() if k != "functions"}, indent=2, ensure_ascii=False
    )
    body = ",\n".join("    " + json.dumps(r, ensure_ascii=False) for r in rows)
    return head[:-2] + ',\n  "functions": [\n' + body + "\n  ]\n}\n"


def _first_section(text: str, start: int) -> int:
    ends = [
        i for i in (text.find("\n### ", start), text.find("\n## ", start)) if i >= 0
    ]
    return min(ends) if ends else len(text)


def _strip_parameters(section: str) -> str:
    """``section`` without its hand-written ``**Parameters:**`` paragraph (a line, or a line and its bullets)."""
    return _PARAMETERS.sub("", section)


def _docs_section(section: str, region: str) -> str:
    """A function section with its generated region in place of the ``<Tier .../>`` line, and the
    ``**Signature:**`` paragraph removed (the region carries the signature; prose after its dash stays).
    """
    sig = _SIGNATURE.search(section)
    if sig:
        prose = sig.group(1).split(" — ", 1)[1].strip() if " — " in sig.group(1) else ""
        keep = (prose[:1].upper() + prose[1:] + "\n\n") if prose else ""
        section = section[: sig.start()] + keep + section[sig.end() :]
    tier = _TIER_LINE.search(section)
    if tier:
        impl = (tier.group(1) or "").strip()
        return (
            section[: tier.start()]
            + region
            + (f"\n{impl}\n" if impl else "")
            + section[tier.end() :]
        )
    return "\n" + region + section


def _docs_page(path: Path, fns, text: str) -> str:
    for fn in fns:
        begin, end = S.mdx_markers(fn.sql_name)
        block = S.render_doc_block(fn)
        if begin in text:
            text = S.replace_region(text, begin, end, block)
            at = text.index(end) + len(end)
            stop = _first_section(text, at)
            text = text[:at] + _strip_parameters(text[at:stop]) + text[stop:]
            continue
        name = fn.python.name if fn.python else fn.sql_name[len("gbx_") :]
        heading = f"### {name}\n"
        at = text.find(heading)
        if at < 0:
            raise LookupError(
                f"{path.relative_to(REPO)}: no section '### {name}' for {fn.sql_name}"
            )
        start = at + len(heading)
        stop = _first_section(text, start)
        section = _docs_section(
            _strip_parameters(text[start:stop]), f"{begin}\n{block}{end}\n"
        )
        text = text[:start] + section + text[stop:]
    return text


def plan(only: Optional[str] = None) -> Dict[Path, str]:
    from databricks.labs.gbx import manifest

    manifest.load.cache_clear()
    man = manifest.load()
    out: Dict[Path, str] = {}

    def want(key: str) -> bool:
        return only in (None, key)

    if want("manifest"):
        out[MANIFEST_JSON] = _canonical_manifest(json.loads(read(MANIFEST_JSON)))
    if want("python"):
        for module, path in S.MODULE_FILES.items():
            out[path] = S.replace_region(
                read(path), S.PY_BEGIN, S.PY_END, S.render_python_module(man, module)
            )
    if want("docs"):
        pages: Dict[Path, list] = {}
        for fn in man.functions.values():
            if fn.status == "stable":
                pages.setdefault(REPO / "docs/docs" / f"{fn.doc.page}.mdx", []).append(
                    fn
                )
        for path, fns in pages.items():
            out[path] = _docs_page(
                path, sorted(fns, key=lambda f: f.sql_name), read(path)
            )
    if want("function-info"):
        merged = S.merge_function_info(
            json.loads(read(FUNCTION_INFO)), S.function_info_entries(man)
        )
        out[FUNCTION_INFO] = json.dumps(merged, indent=2, ensure_ascii=False)
    if want("availability"):
        functions_table, sources_table = S.render_availability(man)
        text = S.replace_region(
            read(AVAILABILITY), *S.mdx_markers("functions"), functions_table
        )
        out[AVAILABILITY] = S.replace_region(
            text, *S.mdx_markers("datasources"), sources_table
        )
    if want("examples"):
        out[EXAMPLES] = EXAMPLES_HEADER + S.render_examples(man)
    if want("counts"):
        readme = REPO / "README.md"
        out[readme] = S.replace_region(
            read(readme), *S.md_markers("counts"), S.render_counts_md(man)
        )
        intro = REPO / "docs/docs/intro.mdx"
        if S.mdx_markers("counts")[0] in read(intro):
            out[intro] = S.replace_region(
                read(intro), *S.mdx_markers("counts"), S.render_counts_mdx(man)
            )
    return out


def _duplicate_defs(path: Path, text: str) -> List[str]:
    seen, findings = set(), []
    for node in ast.parse(text).body:
        if isinstance(node, ast.FunctionDef):
            if node.name in seen:
                findings.append(
                    f"{path.relative_to(REPO)}: {node.name} is defined twice; delete the hand-written def "
                    "(the manifest generates it)"
                )
            seen.add(node.name)
    return findings


def _generated_part(path: Path, text: str) -> str:
    """The text the generator wrote: for function-info.json, the manifest rows only (the legacy generator
    writes the other entries)."""
    if path != FUNCTION_INFO:
        return text
    from databricks.labs.gbx import manifest

    return json.dumps(S.function_info_entries(manifest.load()), ensure_ascii=False)


def check(only: Optional[str] = None) -> List[str]:
    try:
        planned = plan(only)
    except (KeyError, LookupError) as exc:
        return [f"a generated region or docs section is missing: {exc}"]
    findings: List[str] = []
    for path, new in planned.items():
        rel = path.relative_to(REPO)
        old = read(path) if path.exists() else ""
        if old != new:
            diff = difflib.unified_diff(
                old.splitlines(), new.splitlines(), lineterm="", n=0
            )
            first = next(
                (d for d in diff if d[:1] in "+-" and d[:3] not in ("+++", "---")), ""
            )
            findings.append(
                f"{rel}: differs from the manifest ({first[:120]}); run gbx:manifest:gen --write"
            )
        if _MACHINE_PATH.search(_generated_part(path, new)):
            findings.append(f"{rel}: a machine path in generated output")
        if path in S.MODULE_FILES.values():
            findings += _duplicate_defs(path, new)
            if "from databricks.labs.gbx import _api" not in new:
                findings.append(
                    f"{rel}: does not import _api (the generated entries call it)"
                )
    if only is None:
        try:  # the replacement gates
            import check_surfaces
        except ModuleNotFoundError:
            pass
        else:
            findings += check_surfaces.run()
    return findings


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--only", choices=SURFACE_KEYS)
    a = ap.parse_args(argv)
    if a.write == a.check:
        ap.error("pass exactly one of --write / --check")
    if a.check:
        found = check(a.only)
        print("\n".join(found) or "gbx:manifest:gen --check: no drift")
        return 1 if found else 0
    for path, text in plan(a.only).items():
        if not path.exists() or read(path) != text:
            path.write_text(text)
            print(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
