def mdx_markers(key: str) -> Tuple[str, str]:
    return (
        f"{{/* BEGIN GENERATED {key}: edit manifest/functions.json, then run gbx:manifest:gen */}}",
        f"{{/* END GENERATED {key} */}}",
    )


def md_markers(key: str) -> Tuple[str, str]:
    return f"<!-- BEGIN GENERATED {key} -->", f"<!-- END GENERATED {key} -->"


def replace_region(text: str, begin: str, end: str, body: str) -> str:
    i = text.find(begin)
    j = text.find(end, i + len(begin)) if i >= 0 else -1
    if i < 0 or j < 0:
        raise KeyError(begin)
    return text[: i + len(begin)] + "\n" + body + text[j:]


def _wrap(text: str, indent: int) -> List[str]:
    return textwrap.wrap(
        text, width=88 - indent, break_long_words=False, break_on_hyphens=False
    ) or [""]


def _call(callee: str, args: List[str], indent: int) -> List[str]:
    pad = " " * indent
    return [f"{pad}return {callee}(", *[f"{pad}    {a}," for a in args], f"{pad})"]


def _docstring(fn, extras) -> List[str]:
    from databricks.labs.gbx.manifest import usage_args

    out = ['    """' + fn.doc.summary.strip(), ""]
    if fn.params or extras:
        out.append("    Args:")
        if fn.kind == "generator":
            out.append(
                "        df: The input DataFrame; each row is joined with the rows generated from it."
            )
        for i, p in enumerate(fn.params):
            tail = "" if i < fn.min_args else f" SQL default: ``{p.default}``."
            lines = _wrap(f"{p.name}: {p.doc or p.name}{tail}", 8)
            out += ["        " + lines[0]] + ["            " + x for x in lines[1:]]
        out += [f"        {e}: {EXTRA_DOCS[e]}" for e in extras]
        out.append("")
    if fn.doc.returns:
        out += (
            ["    Returns:"] + ["        " + x for x in _wrap(fn.doc.returns, 8)] + [""]
        )
    out += [f"    SQL: ``{fn.sql_name}({usage_args(fn)})``", '    """']
    return out


def render_python_entry(fn) -> str:
    from databricks.labs.gbx.manifest import PY_EXTRAS

    py = fn.python
    extras = PY_EXTRAS[py.extras] if py.extras else ()
    sig = ["df: DataFrame"] if fn.kind == "generator" else []
    sig += [
        f"{p.name}: ColLike" + ("" if i < fn.min_args else " = None")
        for i, p in enumerate(fn.params)
    ]
    sig += [f"{e}: {EXTRA_TYPES[e]} = None" for e in extras]
    ret = "DataFrame" if fn.kind == "generator" else "Column"
    names = [p.name for p in fn.params]
    lines = [
        f"def {py.name}(",
        *[f"    {s}," for s in sig],
        f") -> {ret}:",
    ] + _docstring(fn, extras)
    if fn.kind == "generator":
        lines += _call("_api.table", ["df", f'"{fn.sql_name}"', *names], 4)
    else:
        if extras:
            lines.append(f"    if _api.forced({', '.join(extras)}):")
            lines += _call(
                "_api.force_output", [f'"{fn.sql_name}"', *extras, *names], 8
            )
        lines += _call("_api.call", [f'"{fn.sql_name}"', *names], 4)
    return "\n".join(lines) + "\n"


def render_python_module(man, module: str) -> str:
    fns = sorted(
        (
            f
            for f in man.functions.values()
            if f.python is not None and f.python.module == module
        ),
        key=lambda f: f.python.name,
    )
    return (
        "\n\n"
        + "\n\n".join(render_python_entry(f) for f in fns)
        + ("\n\n" if fns else "")
    )


def _sqltype(t: Optional[str]) -> str:
    return "rows" if t == "ROWS" else (f"`{t}`" if t else "")


def _py_usage(fn) -> str:
    from databricks.labs.gbx.manifest import PY_EXTRAS

    parts = ["df"] if fn.kind == "generator" else []
    parts += [
        p.name if i < fn.min_args else f"{p.name}=None" for i, p in enumerate(fn.params)
    ]
    parts += [
        f"{e}=None" for e in (PY_EXTRAS[fn.python.extras] if fn.python.extras else ())
    ]
    return ", ".join(parts)


def render_doc_block(fn) -> str:
    from databricks.labs.gbx.manifest import usage_args

    rows = [
        (
            "SQL (session)",
            f"`{fn.sql_name}({usage_args(fn)})`",
            _sqltype(fn.returns_session),
        )
    ]
    if "uc" in fn.surfaces:
        rows.append(
            (
                "SQL (Unity Catalog)",
                f"`<catalog>.<schema>.{fn.sql_name}({usage_args(fn)})`",
                _sqltype(fn.returns_uc),
            )
        )
    if fn.python is not None:
        kind = "DataFrame" if fn.kind == "generator" else "Column"
        rows.append(
            (
                "Python",
                f"`{fn.python.module}.functions.{fn.python.name}({_py_usage(fn)})`",
                kind,
            )
        )
    out = [
        f"<Surfaces {' '.join(fn.surfaces)} />",
        "",
        "| Surface | Call | Returns |",
        "|---|---|---|",
    ]
    out += [f"| {a} | {b} | {c} |" for a, b, c in rows]
    if fn.columns:
        out += ["", "Rows: " + ", ".join(f"`{n}` `{t}`" for n, t in fn.columns) + "."]
    if fn.params:
        uc = "uc" in fn.surfaces
        head = (
            "| Parameter | SQL type |"
            + (" UC type |" if uc else "")
            + " Default | Description |"
        )
        out += ["", head, "|---|---|" + ("---|" if uc else "") + "---|---|"]
        for p in fn.params:
            cells = [f"`{p.name}`", " or ".join(f"`{t}`" for t in p.session)]
            if uc:
                cells.append(f"`{p.uc}`" if p.uc else "")
            cells += [f"`{p.default}`" if p.default is not None else "", p.doc]
            out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out) + "\n"


def _info_script():
    """docs/scripts/generate-function-info.py, the one owner of statement splitting and path neutralizing."""
    import importlib.util

    path = REPO / "docs/scripts/generate-function-info.py"
    spec = importlib.util.spec_from_file_location("gbx_generate_function_info", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _strip_comments(stmt: str) -> str:
    """``stmt`` without its ``--`` comments; a ``--`` inside a quoted string stays."""
    out, quote, i = [], None, 0
    while i < len(stmt):
        ch = stmt[i]
        if quote:
            out.append(ch)
            quote = None if ch == quote else quote
        elif ch in "'\"":
            out.append(ch)
            quote = ch
        elif stmt.startswith("--", i):
            i = stmt.find("\n", i)
            if i < 0:
                break
            continue
        else:
            out.append(ch)
        i += 1
    return "".join(out)


def first_statement(sql: str) -> Optional[str]:
    """The first statement naming a gbx_ function, comments stripped (what DESCRIBE shows). Statements split
    on a ``;`` outside quotes and comments, so a ``;`` or ``--`` inside a string literal stays."""
    for stmt in _info_script()._split_sql_statements(sql):
        flat = " ".join(_strip_comments(stmt).split())
        if "gbx_" in flat:
            return flat
    return None


def hand_written_sql_examples() -> Dict[str, str]:
    """The ``<name>_sql_example()`` texts of the docs SQL modules, read without importing them."""
    found: Dict[str, str] = {}
    for path in sorted((REPO / "docs/tests/python/api").glob("*_functions_sql.py")):
        for node in ast.parse(path.read_text()).body:
            if isinstance(node, ast.FunctionDef) and node.name.endswith("_sql_example"):
                ret = next(
                    (n for n in ast.walk(node) if isinstance(n, ast.Return)), None
                )
                if (
                    ret is not None
                    and isinstance(ret.value, ast.Constant)
                    and isinstance(ret.value.value, str)
                ):
                    stmt = first_statement(ret.value.value)
                    if stmt:
                        found["gbx_" + node.name[: -len("_sql_example")]] = stmt
    return found


def _literal(value, param) -> Optional[str]:
    from databricks.labs.gbx import _api

    if value is None or isinstance(value, (bool, int, float, str, bytes, bytearray)):
        return _api._sql_literal(value, param)
    return None  # a fixture (Build) or a structured value: a column of the example view


def example_sql(fn, case) -> str:
    """The SQL of one oracle row. A fixture argument is a column ``c<i>`` of the view ``gbx_example``; an
    aggregate's first argument is its group, so the view holds one row per member (``c0``, or ``c0, c1``)
    and the per-group constants are literals."""
    if fn.kind == "aggregate":
        from databricks.labs.gbx.bench import oracles

        n0 = oracles.group_width(fn.params)
        consts = [_literal(a, fn.params[i + n0]) for i, a in enumerate(case.args[1:])]
        if None in consts:
            raise ValueError(
                f"{fn.sql_name}: oracle row {case.cid!r} has a per-group argument that is not a literal; "
                "pick an example row whose per-group arguments are plain values"
            )
        args = [f"c{i}" for i in range(n0)] + consts
        return f"SELECT {fn.sql_name}({', '.join(args)}) AS out FROM gbx_example"
    args, uses_view = [], False
    for i, a in enumerate(case.args[: len(fn.params)]):
        lit = _literal(a, fn.params[i])
        uses_view = uses_view or lit is None
        args.append(lit if lit is not None else f"c{i}")
    call = f"{fn.sql_name}({', '.join(args)})"
    if fn.kind == "generator":
        return f"SELECT gbx_out.* FROM gbx_example, LATERAL {call} AS gbx_out"
    return f"SELECT {call} AS out" + (" FROM gbx_example" if uses_view else "")


def examples_by_name(man) -> Dict[str, Tuple[str, str, str]]:
    from databricks.labs.gbx.bench import oracles

    out = {}
    for f in man.functions.values():
        if f.status == "stable" and f.example:
            case = next(c for c in oracles.TABLES[f.oracle] if c.cid == f.example)
            out[f.sql_name] = (f.oracle, f.example, example_sql(f, case))
    return out


def _py_str(text: str) -> str:
    """A Python string literal as black writes it: double quotes, unless that needs more escapes."""
    if '"' not in text and "\\" not in text:
        return '"' + text + '"'
    return repr(text)


def render_examples(man) -> str:
    lines = ["EXAMPLES = {"]
    for name, (table, cid, sql) in sorted(examples_by_name(man).items()):
        lines += [
            f'    "{name}": (',
            f'        "{table}",',
            f'        "{cid}",',
            f"        {_py_str(sql)},",
            "    ),",
        ]
    return "\n".join(lines + ["}"]) + "\n"


def function_info_entries(man) -> Dict[str, dict]:
    from databricks.labs.gbx.manifest import usage_args

    neutral = _info_script().neutral_paths
    hand = {n: neutral(t) for n, t in hand_written_sql_examples().items()}
    gen = examples_by_name(man)
    out = {}
    for f in man.functions.values():
        if f.status != "stable":
            continue
        out[f.sql_name] = {
            "examples": "Examples:\n      > "
            + (hand.get(f.sql_name) or gen[f.sql_name][2])
            + ";",
            "usage_args": usage_args(f),
            "description": f.doc.summary,
            "surfaces": list(f.surfaces),
            "since": f.since,
        }
    return out


def merge_function_info(existing: dict, entries: Dict[str, dict]) -> dict:
    """Replace or add the manifest rows; keep every other entry and the package sections, names sorted."""
    sections: Dict[str, Dict[str, dict]] = {}
    current = "rasterx"
    for key, value in existing.get("functions", {}).items():
        if key.startswith("_package_"):
            current = key[len("_package_") :]
            sections.setdefault(current, {})
        else:
            sections.setdefault(current, {})[key] = value
    for name, entry in entries.items():
        # a row stays in the section that holds it; SECTION_OF_PREFIX places a new name only
        held = next((sec for sec, names in sections.items() if name in names), None)
        sections.setdefault(held or SECTION_OF_PREFIX[name.split("_")[1]], {})[
            name
        ] = entry
    out: Dict[str, object] = {}
    for sec, names in sections.items():
        out[f"_package_{sec}"] = f"--- {sec} ---"
        out.update({n: names[n] for n in sorted(names)})
    return {"functions": out}


def render_availability(man) -> Tuple[str, str]:
    yes = "✓"
    rows = [
        "| Function | SQL (session) | SQL (Unity Catalog) | Python | Scala |",
        "|---|---|---|---|---|",
    ]
    for f in sorted(man.functions.values(), key=lambda f: f.sql_name):
        if f.status != "stable":
            continue
        py = f"`{f.python.module}.functions.{f.python.name}`" if f.python else ""
        uc = yes if "uc" in f.surfaces else ""
        sc = yes if "scala" in f.surfaces else ""
        rows.append(f"| `{f.sql_name}` | {yes} | {uc} | {py} | {sc} |")
    ds = ["| Format | Read | Write | Implementation | Page |", "|---|---|---|---|---|"]
    for d in sorted(man.datasources, key=lambda d: d.name):
        if d.status == "stable":
            r = yes if d.kind in ("reader", "reader_writer") else ""
            w = yes if d.kind in ("writer", "reader_writer") else ""
            ds.append(
                f"| `{d.name}` | {r} | {w} | {d.impl} | [{d.page}](../{d.page}) |"
            )
    return "\n".join(rows) + "\n", "\n".join(ds) + "\n"


def all_sql_names(man) -> List[str]:
    names = {f.sql_name for f in man.functions.values() if f.status == "stable"}
    legacy = PKG / "bench/registered_functions.txt"
    if (
        legacy.exists()
    ):  # until every family is in the manifest (deleted in the release-gate cleanup)
        names |= {
            ln.strip()
            for ln in legacy.read_text().splitlines()
            if ln.strip() and not ln.startswith("#")
        }
    return sorted(names)


def render_counts_md(man) -> str:
    names = all_sql_names(man)
    count = {"Functions": len(names)}
    for n in names:
        label = BADGE_OF_PREFIX[n.split("_")[1]]
        count[label] = count.get(label, 0) + 1
    lines = []
    for k in ("Functions", "RasterX", "GridX", "VectorX", "PMTiles"):
        if k in count:
            slug, colour = (
                ("functions", "2e7d32") if k == "Functions" else (k, "1565c0")
            )
            lines.append(
                f"![{k}](https://img.shields.io/badge/{slug}-{count[k]}-{colour})"
            )
    return "\n".join(lines) + "\n"


def render_counts_mdx(man) -> str:
    names = all_sql_names(man)
