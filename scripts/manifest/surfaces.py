def _mdx_cell(text) -> str:
    """Text for a table cell in MDX: the characters MDX or the table would read as markup are escaped."""
    out = str(text) if text else ""
    for a, b in (("|", "\\|"), ("{", "&#123;"), ("}", "&#125;"), ("<", "&lt;"), (">", "&gt;")):
        out = out.replace(a, b)
    return out


def _driver_anchor(kind: str, name: str) -> str:
    """The anchor of a driver's row in the vector or raster table: vector-gpkg, raster-esri-shapefile."""
    return f"{kind}-" + re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def _table(head, rows) -> List[str]:
    return [
        "| " + " | ".join(head) + " |",
        "|" + "---|" * len(head),
        *("| " + " | ".join(r) + " |" for r in rows),
    ]


def _tested_cell(name: str, kind: str) -> str:
    """The "Tested with GeoBrix" cell: the label (CSS tints the row from it) and the entries, or empty."""
    from databricks.labs.gbx.drivers._tested import TESTED_DRIVERS, tested_in

    if not tested_in(name, kind):
        return ""
    e = TESTED_DRIVERS[name][kind]

    def code(entries: str) -> str:
        return " or ".join(f"`{x}`" for x in entries.split(", "))

    text = f"{code(e['read'])} (read)"
    if e["write"]:
        text += f", {code(e['write'])} (write)"
    return f'<span className="gbx-tested">Tested</span> {text}'


def _guidance_cell(d: dict, kind: str, prefix: str = "./") -> str:
    """The "GeoBrix guidance" cell: the note of a driver that has an entry (a built-in to use, a caveat) or that is
    tested as a ``kind`` driver (what GeoBrix does with it), with the pages that cover it. ``prefix`` is the path from
    the page to the docs root (the driver tables are one level down). An untested driver without an entry is empty:
    the intro of its table says what a plain row would."""
    from databricks.labs.gbx.drivers import _guidance
    from databricks.labs.gbx.drivers._tested import tested_in

    if d["driver"] not in _guidance.GUIDANCE and not tested_in(d["driver"], kind):
        return ""
    return _mdx_cell_keep_code(_guidance.guidance_markdown(d, prefix, kind))


def _mdx_cell_keep_code(text: str) -> str:
    """Text for a table cell that already holds code spans and links: only the pipe and the braces are escaped."""
    return text.replace("|", "\\|").replace("{", "&#123;").replace("}", "&#125;")


# The driver tables live on three subpages of docs/docs/gdal-drivers.mdx: kind -> (page path under docs/docs, title).
DRIVER_SUBPAGES = {
    "vector": ("gdal-drivers/vector", "Vector drivers"),
    "raster": ("gdal-drivers/raster", "Raster drivers"),
    "other": ("gdal-drivers/other", "Other drivers"),
}


def _driver_groups(snapshot: dict, kind: str):
    """The drivers of one kind in the three groups of its page: available and tested, available and not tested,
    unavailable (not available in the build, or refused by the policy)."""
    from databricks.labs.gbx.drivers._tested import tested_in

    mine = [d for d in snapshot["drivers"] if d[kind]]
    usable = [d for d in mine if d["available"] and d["allowed"]]
    down = [d for d in mine if not (d["available"] and d["allowed"])]
    tested = [d for d in usable if tested_in(d["driver"], kind)]
    rest = [d for d in usable if not tested_in(d["driver"], kind)]
    return tested, rest, down


def _can(d: dict, kind: str) -> str:
    """The "Can" cell of a driver row: read, write, and (raster page) tile bytes, from the snapshot's flags."""
    can = [w for w, on in (("read", d["read"]), ("write", d["write"])) if on]
    if kind == "raster" and d["tile_bytes"]:
        can.append("tile bytes")
    return " · ".join(can)


def _other_drivers(snapshot: dict) -> list:
    return [d for d in snapshot["drivers"] if not d["raster"] and not d["vector"]]


def render_drivers_page(snapshot: dict) -> str:
    """The generated body of docs/docs/gdal-drivers.mdx, from the committed snapshot of the env wheel's own build
    (``manifest/shipped_drivers.json``, refreshed by test/core/test_drivers.py) and the built-in formats
    (``drivers/_builtin.py``): the built-in formats, and the index of the three driver pages with their counts.
    A built-in format links to its driver's row on the vector or raster page."""
    from databricks.labs.gbx.drivers._builtin import BUILT_IN_FORMATS

    drivers = snapshot["drivers"]
    by_name = {d["driver"]: d for d in drivers}

    def first_link(name: str) -> str:
        kind = "raster" if by_name[name]["raster"] else "vector"
        return f"./{DRIVER_SUBPAGES[kind][0]}#{_driver_anchor(kind, name)}"

    out: List[str] = ["## Formats GeoBrix handles without a GDAL driver", ""]
    out += [
        "These GeoBrix readers, writers and functions do not use the GDAL driver of the same format.",
        "Their path does not depend on the driver rows on the pages below.",
        "A format that GeoBrix reads through rasterio or pyogrio, such as GeoTIFF or GeoPackage, uses its driver.",
        "",
    ]
    rows = []
    for f in BUILT_IN_FORMATS:
        drv = f["driver"]
        cell = f"[`{drv}`]({first_link(drv)})" if drv in by_name else "none"
        rows.append(
            [
                f'<Link id="{f["anchor"]}"></Link>{_mdx_cell(f["format"])}',
                cell,
                _mdx_cell(f["uses"]),
                _mdx_cell(f["where"]),
            ]
        )
    out += _table(
        ["Format", "GDAL driver", "What GeoBrix uses instead", "Where"], rows
    )
    out += ["", "## Driver tables", ""]
    out += [
        "The drivers of the env wheel's GDAL build are on three pages, by what they handle.",
        "Each page of vector or raster drivers has three groups: available and tested, available and not tested, and unavailable.",
        "",
    ]
    index = []
    for kind in ("vector", "raster"):
        tested, rest, down = _driver_groups(snapshot, kind)
        path, title = DRIVER_SUBPAGES[kind]
        index.append(
            f"- [{title}](./{path}): {len(tested) + len(rest) + len(down)} drivers, "
            f"{len(tested)} tested with GeoBrix, {len(rest)} available and not tested, {len(down)} unavailable."
        )
    other = _other_drivers(snapshot)
    path, title = DRIVER_SUBPAGES["other"]  # always listed: the page also holds the opt-in drivers
    index.append(
        f"- [{title}](./{path}): {len(other)} drivers that handle neither rasters nor vectors, "
        "and the drivers that are off by default."
    )
    out += index
    return "\n".join(out).rstrip("\n") + "\n"


def render_drivers_subpage(snapshot: dict, kind: str) -> str:
    """The generated body of one driver page (docs/docs/gdal-drivers/<kind>.mdx): the tables of the vector or raster
    drivers in their three groups, or the one table of the other drivers. A driver of both kinds links to its row on
    the other page. The columns are few so that the table fits the content width: one \"Can\" cell holds read, write and tile bytes."""
    yes = "✓"
    out: List[str] = []
    if kind == "other":
        out += ["## Other drivers", ""]
        others = _other_drivers(snapshot)
        if others:
            out += _table(
                ["Driver", "Description", "Can"],
                [
                    [
                        f"`{d['driver']}`",
                        _mdx_cell(d["description"]),
                        _can(d, kind),
                    ]
                    for d in others
                ],
            )
        else:
            out += ["None."]
        out += _opt_in_section(snapshot.get("opt_in", []))
        return "\n".join(out).rstrip("\n") + "\n"

    other = "raster" if kind == "vector" else "vector"

    def row_cells(d, head, with_tested):
        name = d["driver"]
        cell = [
            f'<Link id="{_driver_anchor(kind, name)}"></Link>`{name}`',
            _mdx_cell(d["description"]),
            _can(d, kind),
        ]
        req = _mdx_cell(d["requires"])
        if d[other]:  # a driver of both kinds links to its row on the other page
            link = (
                f"Also a {other} driver: [see the {other} page]"
                f"(./{other}#{_driver_anchor(other, name)})."
            )
            req = f"{req} {link}".strip()
        cell.append(req)
        if with_tested:
            cell.append(_tested_cell(name, kind))
        if "GeoBrix guidance" in head:
            cell.append(_guidance_cell(d, kind, "../"))
        return cell

    tested, rest, down = _driver_groups(snapshot, kind)
    reader = {
        "raster": "`raster_gbx` detects the format from the file, so it takes no driver option.",
        "vector": "`vector_gbx` reads a driver when you set its `driverName` option to the GDAL driver name.",
    }[kind]
    for title, group, intro in (
        (
            f"Available {kind} drivers: tested with GeoBrix",
            tested,
            f"GeoBrix's extended driver tests cover these {kind} drivers in this release.",
        ),
        (
            f"Available {kind} drivers: not tested with GeoBrix",
            rest,
            f"These {kind} drivers are registered, and they may work with GeoBrix, but they are use-at-your-own-risk. "
            f"{reader} "
            "Plain GDAL, `from osgeo import gdal`, may suit them better than GeoBrix's distributed readers and writers.",
        ),
        (f"Unavailable {kind} drivers", down, ""),
    ):
        out.extend([f"## {title}", ""])
        if not group:
            out.extend([f"No {kind} driver is unavailable in the env wheel." if not intro else "None.", ""])
            continue
        if intro:
            out.extend([intro, ""])
        is_tested = group is tested
        head = ["Driver", "Description", "Can"]
        head.append("Why" if group is down else "Requires")
        if is_tested:
            head.append("Tested with GeoBrix")
        if group is not down:
            head.append("GeoBrix guidance")
        # the wrapper scopes the column widths in custom.css to these tables
        out.extend(['<div className="gbx-driver-table">', ""])
        out.extend(_table(head, [row_cells(d, head, is_tested) for d in group]))
        out.extend(["", "</div>"])
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def _opt_in_section(opt_in: list) -> List[str]:
    """The last section of docs/docs/gdal-drivers/other.mdx: the drivers the policy refuses, from the snapshot's
    ``opt_in`` rows (read from a build with the policy off) and the policy's own reason classes."""
    yes = "✓"
    out = [
        "",
        "## GeoBrix Opt-In Drivers",
        "",
        "These drivers are off by default. You can opt in to them, and then you own the risk.",
        "GeoBrix keeps each one off because it reaches a network service, runs a stored pipeline, or acts on what a file names.",
        "A file that another principal wrote can then make your cluster send requests or run a pipeline.",
        "",
        "### What the policy does",
        "",
        "- **It covers the whole Python process.** It is not limited to GeoBrix functions.",
        "  It adds these drivers to `GDAL_SKIP` and removes them from each GDAL that the process has loaded.",
        "  A direct `from osgeo import gdal` in the same process therefore lacks them too.",
        "- **It starts when GeoBrix is imported.** The import adds the drivers to `GDAL_SKIP`, and sets the two VRT settings.",
        "  The first GeoBrix use of GDAL completes it. The env wheel's startup file only prepares the native libraries.",
        "  The call `register(spark)` does not start the policy itself, because the import has done it.",
        "- **To opt in, set `GBX_GDAL_DRIVER_POLICY=off` before `import databricks.labs.gbx`.**",
        "  A value set after the import has no effect. GeoBrix has already added the drivers to `GDAL_SKIP`.",
        "- **Set it where each process can read it.** The driver and every executor read the variable in their own Python process.",
        "  Set it in the cluster's environment variables, or the job cluster's, to reach all of them.",
        "  A notebook assignment of `os.environ` before the import reaches the driver only. A worker still applies the policy.",
        "  On the JVM, set `spark.databricks.labs.gbx.gdal.driver_policy=off` in the Spark config, or the same variable in the cluster's environment.",
        "- **Off removes the whole defence for that process.** The VRT raw-band and Python settings stay as GDAL has them.",
        "  Prefer a separate process or job for work on data you trust and that needs one of these drivers.",
        "- **The live view changes too.** `gbx_drivers()` lists these drivers only when the policy is off.",
        "",
        "See [The policy covers the whole process](../security#the-policy-covers-the-whole-process) on the Security page.",
        "",
    ]
    if not opt_in:
        return out + ["None.", ""]
    rows = []
    for r in opt_in:
        kind = " and ".join(k for k in ("raster", "vector") if r[k]) or "none"
        rows.append(
            [
                f"`{r['driver']}`",
                _mdx_cell(r["description"] or r["driver"]),
                kind,
                _mdx_cell(f"{r['class']}. {r['why']}"),
                yes if r["in_build"] else "no",
            ]
        )
    out += _table(
        ["Driver", "Description", "Kind", "Why it is off by default", "In the shipped build"],
        rows,
    )
    out.append("")
    return out
