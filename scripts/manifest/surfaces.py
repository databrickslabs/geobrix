def replace_region(text: str, begin: str, end: str, body: str) -> str:
    i = text.find(begin)
    j = text.find(end, i + len(begin)) if i >= 0 else -1
    if i < 0 or j < 0:
        raise KeyError(begin)
    return text[: i + len(begin)] + "\n" + body + text[j:]


def _wrap(text: str, indent: int) -> List[str]:
    return textwrap.wrap(
        text, width=88 - indent, break_long_words=False, break_on_hyphens=False
    ) or [""]


def _call(callee: str, args: List[str], indent: int) -> List[str]:
    pad = " " * indent
    return [f"{pad}return {callee}(", *[f"{pad}    {a}," for a in args], f"{pad})"]


def _docstring(fn, extras, group=None) -> List[str]:
    from databricks.labs.gbx.manifest import usage_args

    out = ['    """' + fn.doc.summary.strip(), ""]
    if fn.params or extras:
        out.append("    Args:")
        if fn.table_input is not None:
            cols = ", ".join(f"``{n}``" for n, _ in fn.table_input.columns)
            keys = ", ".join(f"``{k}``" for k in fn.table_input.partition_by)
            lines = _wrap(
                f"df: The input DataFrame, with the columns {cols} (others are left out); it is partitioned by {keys}.",
                8,
            )
            out += ["        " + lines[0]] + ["            " + x for x in lines[1:]]
        elif fn.kind == "generator" and not fn.source:
            out.append(
                "        df: The input DataFrame; each row is joined with the rows generated from it."
            )
        for i, p in enumerate(fn.params):
            if fn.table_input is not None and i == 0:
                continue  # the table argument is `df`
            tail = "" if i < fn.min_args else f" SQL default: ``{p.default}``."
            lines = _wrap(f"{p.name}: {p.doc or p.name}{tail}", 8)
            out += ["        " + lines[0]] + ["            " + x for x in lines[1:]]
        out += [
            f"        {e}: {GROUP_EXTRA_DOCS.get((group, e), EXTRA_DOCS[e])}"
            for e in extras
        ]
        out.append("")
    if fn.doc.returns:
        out += (
            ["    Returns:"] + ["        " + x for x in _wrap(fn.doc.returns, 8)] + [""]
        )
    out += [f"    SQL: ``{fn.sql_name}({usage_args(fn)})``", '    """']
    return out


# The Python type of a table function's constant: it is a literal of the call (`_api.table_by` renders it into the
# SQL text), so a Column is not accepted and the hint says so.
LITERAL_TYPES = {
    "DOUBLE": "float",
    "FLOAT": "float",
    "INT": "int",
    "BIGINT": "int",
    "SMALLINT": "int",
    "TINYINT": "int",
    "STRING": "str",
    "BOOLEAN": "bool",
    "BINARY": "bytes",
}


def _py_type(p, literal: bool) -> str:
    """The annotation of one parameter: ``ColLike`` (a column or a name), or a plain Python type for the constants
    of a table function."""
    return LITERAL_TYPES.get(p.session[0], "object") if literal else "ColLike"


def render_python_entry(fn) -> str:
    from databricks.labs.gbx.manifest import PY_EXTRAS

    py = fn.python
    extras = PY_EXTRAS[py.extras] if py.extras else ()
    sig = ["df: DataFrame"] if fn.kind == "generator" and not fn.source else []
    # a table function's first parameter is its table argument, which `df` stands for
    skip = 1 if fn.table_input is not None else 0
    sig += [
        f"{p.name}: {_py_type(p, fn.table_input is not None or fn.source)}"
        + ("" if i < fn.min_args else " = None")
        for i, p in enumerate(fn.params)
        if i >= skip
    ]
    sig += [f"{e}: {EXTRA_TYPES[e]} = None" for e in extras]
    ret = "DataFrame" if fn.kind == "generator" else "Column"
    names = [p.name for p in fn.params[skip:]]
    lines = [
        f"def {py.name}(",
        *[f"    {s}," for s in sig],
        f") -> {ret}:",
    ] + _docstring(fn, extras, py.extras)
    if fn.table_input is not None:
        lines += _call("_api.table_by", ["df", f'"{fn.sql_name}"', *names], 4)
    elif fn.source:
        lines += _call("_api.source", [f'"{fn.sql_name}"', *names], 4)
    elif fn.kind == "generator":
        lines += _call("_api.table", ["df", f'"{fn.sql_name}"', *names], 4)
    else:
        if py.extras == "materialize":
            # the row's `extra_impl` is the whole Python entry: an unset keyword is its default, not the SQL name's
            lines += _call(
                "_api.extra_call",
                [f'"{fn.sql_name}"', f"({', '.join(extras)},)", *names],
                4,
            )
            return "\n".join(lines) + "\n"
        if extras:
            lines.append(f"    if _api.forced({', '.join(extras)}):")
            lines += _call(
                "_api.force_output", [f'"{fn.sql_name}"', *extras, *names], 8
            )
        lines += _call("_api.call", [f'"{fn.sql_name}"', *names], 4)
    return "\n".join(lines) + "\n"


def render_python_module(man, module: str) -> str:
    fns = sorted(
        (
            f
            for f in man.functions.values()
            if f.python is not None and f.python.module == module
        ),
        key=lambda f: f.python.name,
    )
    return (
        "\n\n"
        + "\n\n".join(render_python_entry(f) for f in fns)
        + ("\n\n" if fns else "")
    )


def _sqltype(t: Optional[str]) -> str:
    return "rows" if t == "ROWS" else (f"`{t}`" if t else "")


def _py_usage(fn) -> str:
    from databricks.labs.gbx.manifest import PY_EXTRAS

    parts = ["df"] if fn.kind == "generator" and not fn.source else []
    skip = 1 if fn.table_input is not None else 0
    parts += [
        p.name if i < fn.min_args else f"{p.name}=None"
        for i, p in enumerate(fn.params)
        if i >= skip
    ]
    parts += [
        f"{e}=None" for e in (PY_EXTRAS[fn.python.extras] if fn.python.extras else ())
    ]
    return ", ".join(parts)


